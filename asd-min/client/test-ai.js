import { Chess } from 'chess.js';
import { getBestMoveAsync } from './src/utils/aiEngine.js';

console.log('Testing AI Engine across difficulty levels...');

const chess = new Chess();

async function runTests() {
  for (let level = 1; level <= 4; level++) {
    const move = await getBestMoveAsync(chess, level);
    console.assert(move && move.from && move.to, `Level ${level} must return valid move`);
    const isLegal = chess.moves({ verbose: true }).some(m => m.from === move.from && m.to === move.to);
    console.assert(isLegal, `Move ${move.from}->${move.to} generated by AI level ${level} must be legal`);
    console.log(`✓ AI Level ${level} generated legal move: ${move.from}->${move.to}`);
  }

  // Tactical test: Scholar's mate defense or obvious capture
  const tacticalGame = new Chess();
  tacticalGame.move('e4');
  tacticalGame.move('e5');
  tacticalGame.move('Qh5');
  tacticalGame.move('Nc6');
  tacticalGame.move('Bc4'); // Threatening Qxf7#
  // Black needs to defend f7 (e.g. g6 or Qe7 or Nf6)
  const defensiveMove = await getBestMoveAsync(tacticalGame, 4);
  console.assert(defensiveMove !== null, 'Defensive move should be found');
  console.log(`✓ AI Level 4 tactical move against mate threat: ${defensiveMove.from}->${defensiveMove.to}`);

  console.log('ALL AI ENGINE TESTS PASSED SUCCESSFULLY!');
}

runTests();

